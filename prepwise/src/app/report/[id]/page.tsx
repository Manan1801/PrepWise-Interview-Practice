"use client";
import { use, useEffect, useState } from "react";
import Link from "next/link";
import { useRouter } from "next/navigation";
import { getSession, newSession, saveSession } from "@/lib/storage";
import { reportCall } from "@/lib/api";
import { DIMENSIONS, getTrack } from "@/lib/tracks";
import { ScoreRing, scoreTone, scoreWord } from "@/components/ScoreRing";
import type { InterviewSession, SessionReport } from "@/lib/types";

export default function ReportPage({ params }: { params: Promise<{ id: string }> }) {
  const { id } = use(params);
  const router = useRouter();
  const [s, setS] = useState<InterviewSession | null | undefined>(undefined);
  const [loading, setLoading] = useState(false);
  const [open, setOpen] = useState<number | null>(0);

  useEffect(() => {
    setS(getSession(id) ?? null);
  }, [id]);

  async function generate() {
    if (!s) return;
    setLoading(true);
    try {
      const report: SessionReport = await reportCall(s);
      const next = { ...s, report, status: "ended" as const };
      saveSession(next);
      setS(next);
    } catch {
      alert("Couldn't generate the report — please check your connection and try again.");
    } finally {
      setLoading(false);
    }
  }

  function again() {
    if (!s) return;
    const n = newSession(s.config, s.mode);
    saveSession(n);
    router.push(`/interview/${n.id}`);
  }

  if (s === undefined) return <p className="text-muted">Loading…</p>;
  if (s === null)
    return (
      <div className="card mx-auto max-w-md p-8 text-center">
        <p className="font-medium">Report not found in this browser.</p>
        <Link href="/progress" className="btn-primary mt-5">Go to my progress</Link>
      </div>
    );

  const r = s.report;
  const answers = s.turns.filter((t) => t.role === "candidate" && t.metrics);
  const totWords = answers.reduce((a, t) => a + (t.metrics?.words ?? 0), 0);
  const totFill = answers.reduce((a, t) => a + (t.metrics?.fillers ?? 0), 0);
  const voiced = answers.filter((t) => t.metrics?.usedVoice);
  const voiceSecs = voiced.reduce((a, t) => a + t.metrics!.seconds, 0);
  const wpm = voiceSecs ? Math.round(voiced.reduce((a, t) => a + t.metrics!.words, 0) / (voiceSecs / 60)) : null;
  const fillerAgg: Record<string, number> = {};
  answers.forEach((t) => Object.entries(t.metrics?.fillerList ?? {}).forEach(([k, v]) => (fillerAgg[k] = (fillerAgg[k] ?? 0) + v)));
  const topFillers = Object.entries(fillerAgg).sort((a, b) => b[1] - a[1]).slice(0, 4);

  return (
    <div className="mx-auto max-w-4xl space-y-6">
      <div className="flex flex-wrap items-end justify-between gap-3">
        <div>
          <p className="eyebrow">Feedback report</p>
          <h1 className="mt-1 text-3xl font-semibold tracking-tight">
            {s.config.role || getTrack(s.config.track).name}
            {s.config.company && <span className="text-muted"> · {s.config.company}</span>}
          </h1>
          <p className="mt-1 text-sm text-muted">{new Date(s.createdAt).toLocaleString()}</p>
        </div>
        <div className="flex gap-2 print:hidden">
          <button className="btn-ghost" onClick={() => window.print()}>Save as PDF</button>
          <button className="btn-primary" onClick={again}>Practise again</button>
        </div>
      </div>

      {!r ? (
        <div className="card p-10 text-center">
          <p className="font-medium">The report hasn&apos;t been generated yet.</p>
          <button className="btn-primary mt-5" onClick={generate} disabled={loading}>{loading ? "Generating…" : "Generate report"}</button>
        </div>
      ) : (
        <>
          {/* Overview */}
          <section className="card flex flex-col gap-6 p-6 sm:flex-row sm:items-center">
            <ScoreRing score={r.overall} />
            <div>
              <div className="text-sm font-semibold" style={{ color: scoreTone(r.overall) }}>{scoreWord(r.overall)}</div>
              <p className="mt-1 text-[15px] leading-relaxed">{r.summary}</p>
              {r.generatedBy === "offline" && <p className="mt-2 text-xs text-muted">Generated by the built-in rule-based coach (AI was unavailable).</p>}
            </div>
          </section>

          <div className="grid gap-6 md:grid-cols-[1.4fr_1fr]">
            {/* Skills */}
            <section className="card p-6">
              <h2 className="font-semibold">Skill breakdown</h2>
              <div className="mt-5 space-y-5">
                {r.dimensions.map((d) => (
                  <div key={d.key}>
                    <div className="flex items-baseline justify-between text-sm">
                      <span className="font-medium" title={DIMENSIONS[d.key]?.desc}>{DIMENSIONS[d.key]?.label ?? d.key}</span>
                      <span className="font-semibold" style={{ color: scoreTone(d.score) }}>{d.score}/10</span>
                    </div>
                    <div className="mt-1.5 h-2 rounded-full bg-line">
                      <div className="h-2 rounded-full" style={{ width: `${d.score * 10}%`, background: scoreTone(d.score) }} />
                    </div>
                    <p className="mt-1.5 text-sm text-muted">{d.note}</p>
                  </div>
                ))}
              </div>
            </section>

            {/* Delivery */}
            <section className="grid content-start gap-3">
              <Stat label="Speaking pace" value={wpm ? `${wpm} wpm` : "—"} sub={wpm ? (wpm < 100 ? "A bit slow — aim for 110–160" : wpm > 170 ? "A bit fast — slow down" : "Comfortable (110–160)") : "No spoken answers"} />
              <Stat label="Filler words" value={String(totFill)} sub={topFillers.map(([k, v]) => `“${k}” ×${v}`).join(", ") || "None — nice 🎉"} />
              <Stat label="Words in your answers" value={String(totWords)} sub={`${r.questions.length} question${r.questions.length === 1 ? "" : "s"} answered`} />
            </section>
          </div>

          {/* Questions */}
          <section className="space-y-3">
            <h2 className="text-lg font-semibold">Question by question</h2>
            {r.questions.map((q, i) => {
              const ans = s.turns.filter((t) => t.qIndex === q.qIndex && t.role === "candidate" && t.kind === "answer");
              const isOpen = open === i;
              return (
                <div key={i} className="card overflow-hidden">
                  <button className="flex w-full items-start gap-4 p-5 text-left hover:bg-bg/60" onClick={() => setOpen(isOpen ? null : i)} aria-expanded={isOpen}>
                    <span className="grid h-10 w-10 shrink-0 place-items-center rounded-xl text-sm font-bold" style={{ background: "var(--bg)", color: scoreTone(q.score) }}>
                      {q.score}
                    </span>
                    <span className="min-w-0 flex-1">
                      {q.competency && <span className="block text-xs font-semibold uppercase tracking-wide text-brand">{q.competency}</span>}
                      <span className="mt-0.5 block font-medium leading-snug">{q.question}</span>
                    </span>
                    <span className={`mt-1 text-muted transition ${isOpen ? "rotate-180" : ""}`} aria-hidden>⌄</span>
                  </button>
                  {isOpen && (
                    <div className="space-y-5 border-t border-line p-5 text-sm">
                      <div className="grid gap-4 sm:grid-cols-2">
                        <List title="What worked" items={q.strengths} tone="good" />
                        <List title="What to improve" items={q.improvements} tone="warn" />
                      </div>
                      {s.plan?.items[q.qIndex] && (
                        <div>
                          <div className="mb-2 text-xs font-semibold uppercase tracking-wide text-muted">What the interviewer was looking for</div>
                          <div className="flex flex-wrap gap-1.5">
                            {s.plan.items[q.qIndex].expectedPoints.map((p) => (
                              <span key={p} className="rounded-full border border-line px-2.5 py-1 text-xs">{p}</span>
                            ))}
                          </div>
                        </div>
                      )}
                      <div className="rounded-xl bg-brand-soft p-4">
                        <div className="mb-2 font-semibold">How a strong answer could be structured</div>
                        <ol className="list-decimal space-y-1.5 pl-5">{q.betterAnswerOutline.map((b, j) => <li key={j}>{b}</li>)}</ol>
                      </div>
                      {ans.length > 0 && (
                        <details className="group">
                          <summary className="cursor-pointer text-muted hover:text-ink">Show your answer{ans.length > 1 ? `s (${ans.length})` : ""}</summary>
                          <div className="mt-2 space-y-2">
                            {ans.map((a) => (
                              <p key={a.id} className="whitespace-pre-wrap rounded-xl border border-line p-3">{a.text}</p>
                            ))}
                          </div>
                        </details>
                      )}
                    </div>
                  )}
                </div>
              );
            })}
          </section>

          {/* Next */}
          <section className="card p-6">
            <h2 className="text-lg font-semibold">Your next practice plan</h2>
            <ol className="mt-4 space-y-3">
              {r.nextSteps.map((n, i) => (
                <li key={i} className="flex gap-3 text-sm">
                  <span className="grid h-6 w-6 shrink-0 place-items-center rounded-full bg-brand text-xs font-semibold text-white dark:text-black">{i + 1}</span>
                  <span className="pt-0.5">{n}</span>
                </li>
              ))}
            </ol>
            <div className="mt-6 flex gap-2 print:hidden">
              <button className="btn-primary" onClick={again}>Practise again</button>
              <Link href="/progress" className="btn-ghost">See my progress</Link>
            </div>
          </section>
        </>
      )}
    </div>
  );
}

function Stat({ label, value, sub }: { label: string; value: string; sub?: string }) {
  return (
    <div className="card p-5">
      <div className="text-xs font-medium uppercase tracking-wide text-muted">{label}</div>
      <div className="mt-1 text-2xl font-semibold">{value}</div>
      {sub && <div className="mt-0.5 text-xs text-muted">{sub}</div>}
    </div>
  );
}

function List({ title, items, tone }: { title: string; items: string[]; tone: "good" | "warn" }) {
  return (
    <div className={`rounded-xl p-4 ${tone === "good" ? "bg-good-soft" : "bg-warn-soft"}`}>
      <div className={`mb-2 font-semibold ${tone === "good" ? "text-good" : "text-warn"}`}>{title}</div>
      <ul className="list-disc space-y-1 pl-5">{items.length ? items.map((x, i) => <li key={i}>{x}</li>) : <li className="text-muted">—</li>}</ul>
    </div>
  );
}
