"use client";
import { use, useEffect, useState } from "react";
import Link from "next/link";
import { useRouter } from "next/navigation";
import { getSession, newSession, saveSession } from "@/lib/storage";
import { reportCall } from "@/lib/api";
import { DIMENSIONS, getTrack } from "@/lib/tracks";
import type { InterviewSession, SessionReport } from "@/lib/types";

const tone = (s: number) => (s >= 7 ? "text-good" : s >= 5 ? "text-warn" : "text-bad");
const bar = (s: number) => (s >= 7 ? "bg-good" : s >= 5 ? "bg-warn" : "bg-bad");

export default function ReportPage({ params }: { params: Promise<{ id: string }> }) {
  const { id } = use(params);
  const router = useRouter();
  const [s, setS] = useState<InterviewSession | null | undefined>(undefined);
  const [loading, setLoading] = useState(false);
  const [open, setOpen] = useState<number | null>(0);

  useEffect(() => {
    setS(getSession(id) ?? null);
  }, [id]);

  async function generate() {
    if (!s) return;
    setLoading(true);
    try {
      const report: SessionReport = await reportCall(s);
      const next = { ...s, report, status: "ended" as const };
      saveSession(next);
      setS(next);
    } catch {
      alert("Couldn't generate the report — please check your connection and try again.");
    } finally {
      setLoading(false);
    }
  }

  function again() {
    if (!s) return;
    const n = newSession(s.config, s.mode);
    saveSession(n);
    router.push(`/interview/${n.id}`);
  }

  if (s === undefined) return <p className="text-muted">Loading…</p>;
  if (s === null)
    return (
      <div className="card mx-auto max-w-md p-6 text-center">
        <p>Report not found in this browser.</p>
        <Link href="/progress" className="btn-primary mt-4">Go to my progress</Link>
      </div>
    );

  const r = s.report;
  const answers = s.turns.filter((t) => t.role === "candidate" && t.metrics);
  const totWords = answers.reduce((a, t) => a + (t.metrics?.words ?? 0), 0);
  const totFill = answers.reduce((a, t) => a + (t.metrics?.fillers ?? 0), 0);
  const voiced = answers.filter((t) => t.metrics?.usedVoice);
  const wpm = voiced.length ? Math.round(voiced.reduce((a, t) => a + t.metrics!.words, 0) / (voiced.reduce((a, t) => a + t.metrics!.seconds, 0) / 60)) : null;
  const fillerAgg: Record<string, number> = {};
  answers.forEach((t) => Object.entries(t.metrics?.fillerList ?? {}).forEach(([k, v]) => (fillerAgg[k] = (fillerAgg[k] ?? 0) + v)));
  const topFillers = Object.entries(fillerAgg).sort((a, b) => b[1] - a[1]).slice(0, 4);

  return (
    <div className="mx-auto max-w-3xl space-y-6">
      <div className="flex flex-wrap items-end justify-between gap-3">
        <div>
          <p className="text-sm text-muted">
            {s.config.role || getTrack(s.config.track).name}{s.config.company && ` · ${s.config.company}`} · {new Date(s.createdAt).toLocaleString()}
          </p>
          <h1 className="text-2xl font-semibold">Your feedback report</h1>
        </div>
        <div className="flex gap-2">
          <button className="btn-ghost" onClick={() => window.print()}>Save as PDF</button>
          <button className="btn-primary" onClick={again}>Practice again</button>
        </div>
      </div>

      {!r ? (
        <div className="card p-6 text-center">
          <p>The report hasn&apos;t been generated yet.</p>
          <button className="btn-primary mt-4" onClick={generate} disabled={loading}>{loading ? "Generating…" : "Generate report"}</button>
        </div>
      ) : (
        <>
          <section className="card grid gap-6 p-5 sm:grid-cols-[auto_1fr] sm:items-center">
            <div className="text-center">
              <div className={`text-5xl font-semibold ${tone(r.overall)}`}>{r.overall}<span className="text-xl text-muted">/10</span></div>
              <div className="mt-1 text-xs text-muted">Overall</div>
            </div>
            <div>
              <p className="leading-relaxed">{r.summary}</p>
              {r.generatedBy === "offline" && <p className="mt-2 text-xs text-muted">Generated by the offline rule-based coach.</p>}
            </div>
          </section>

          <section className="card p-5">
            <h2 className="mb-4 font-medium">Skill breakdown</h2>
            <div className="space-y-4">
              {r.dimensions.map((d) => (
                <div key={d.key}>
                  <div className="flex justify-between text-sm">
                    <span className="font-medium" title={DIMENSIONS[d.key]?.desc}>{DIMENSIONS[d.key]?.label ?? d.key}</span>
                    <span className={tone(d.score)}>{d.score}/10</span>
                  </div>
                  <div className="mt-1 h-2 rounded-full bg-line">
                    <div className={`h-2 rounded-full ${bar(d.score)}`} style={{ width: `${d.score * 10}%` }} />
                  </div>
                  <p className="mt-1 text-sm text-muted">{d.note}</p>
                </div>
              ))}
            </div>
          </section>

          <section className="grid gap-3 sm:grid-cols-4">
            <Stat label="Words spoken/typed" value={String(totWords)} />
            <Stat label="Speaking pace" value={wpm ? `${wpm} wpm` : "—"} sub={wpm ? (wpm < 100 ? "a bit slow" : wpm > 170 ? "a bit fast" : "comfortable (110–160)") : "no voice answers"} />
            <Stat label="Filler words" value={String(totFill)} sub={topFillers.map(([k, v]) => `${k}×${v}`).join(", ") || "none 🎉"} />
            <Stat label="Questions" value={String(r.questions.length)} />
          </section>

          <section className="space-y-3">
            <h2 className="font-medium">Question by question</h2>
            {r.questions.map((q, i) => {
              const ans = s.turns.filter((t) => t.qIndex === q.qIndex && t.role === "candidate");
              const isOpen = open === i;
              return (
                <div key={i} className="card">
                  <button className="flex w-full items-start justify-between gap-4 p-4 text-left" onClick={() => setOpen(isOpen ? null : i)} aria-expanded={isOpen}>
                    <span>
                      <span className="text-muted">Q{q.qIndex + 1}.</span> {q.question}
                      {q.competency && <span className="mt-1 block text-xs text-muted">Tested: {q.competency}</span>}
                    </span>
                    <span className={`shrink-0 font-semibold ${tone(q.score)}`}>{q.score}/10</span>
                  </button>
                  {isOpen && (
                    <div className="space-y-4 border-t border-line p-4 text-sm">
                      <div className="grid gap-4 sm:grid-cols-2">
                        <List title="What worked" items={q.strengths} color="text-good" />
                        <List title="What to improve" items={q.improvements} color="text-warn" />
                      </div>
                      {s.plan?.items[q.qIndex] && (
                        <div className="text-xs text-muted">
                          <span className="font-medium text-ink">What the interviewer was looking for: </span>
                          {s.plan.items[q.qIndex].expectedPoints.join(" · ")}
                        </div>
                      )}
                      <div className="rounded-xl bg-brand-soft p-3">
                        <div className="mb-1 font-medium">How a strong answer could be structured</div>
                        <ol className="list-decimal space-y-1 pl-5">{q.betterAnswerOutline.map((b, j) => <li key={j}>{b}</li>)}</ol>
                      </div>
                      <details>
                        <summary className="cursor-pointer text-muted">Show your answers ({ans.length})</summary>
                        <div className="mt-2 space-y-2">
                          {ans.map((a) => (
                            <p key={a.id} className="rounded-lg border border-line p-2 whitespace-pre-wrap">{a.text}</p>
                          ))}
                        </div>
                      </details>
                    </div>
                  )}
                </div>
              );
            })}
          </section>

          <section className="card p-5">
            <h2 className="mb-3 font-medium">Your next practice plan</h2>
            <ol className="list-decimal space-y-2 pl-5 text-sm">{r.nextSteps.map((n, i) => <li key={i}>{n}</li>)}</ol>
            <div className="mt-4 flex gap-2">
              <button className="btn-primary" onClick={again}>Practice again</button>
              <Link href="/progress" className="btn-ghost">See progress</Link>
            </div>
          </section>
        </>
      )}
    </div>
  );
}

function Stat({ label, value, sub }: { label: string; value: string; sub?: string }) {
  return (
    <div className="card p-4">
      <div className="text-xs text-muted">{label}</div>
      <div className="mt-1 text-xl font-semibold">{value}</div>
      {sub && <div className="mt-0.5 text-xs text-muted">{sub}</div>}
    </div>
  );
}

function List({ title, items, color }: { title: string; items: string[]; color: string }) {
  return (
    <div>
      <div className={`mb-1 font-medium ${color}`}>{title}</div>
      <ul className="list-disc space-y-1 pl-5">{items.length ? items.map((x, i) => <li key={i}>{x}</li>) : <li className="text-muted">—</li>}</ul>
    </div>
  );
}
